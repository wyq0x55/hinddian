"""Shared config + HTTP client for host hooks (stdlib only; runs on every user machine).

Canonical source: hooks/ in the hinddian repo. Copies under plugins/, skills/ and adapters/
are generated by tools/sync_hooks.py — edit here, then run it.

No built-in server address. Settings resolve, first match wins:
  1. env HINDDIAN_MEMORY_URL / HINDDIAN_MCP_TOKEN / HINDDIAN_CA_FILE / HINDDIAN_ALLOW_INSECURE
  2. Claude Code plugin options (CLAUDE_PLUGIN_OPTION_<same name>)
  3. ~/.config/hinddian/config.json  — written by `setup.py` (keys: url, token, ca_file, allow_insecure)
Session text and the token are never sent over plain http to a non-loopback host unless
allow_insecure. A self-signed / private-CA server cert is trusted via ca_file (added to, not
replacing, the system CAs).
"""
from __future__ import annotations

import json
import os
import ssl
import subprocess
import sys
import urllib.parse
import urllib.request
from pathlib import Path
from typing import Any

HERE = Path(__file__).resolve().parent
LOOPBACK = {"127.0.0.1", "localhost", "::1"}
_FILE_KEYS = {
    "HINDDIAN_MEMORY_URL": "url",
    "HINDDIAN_MCP_TOKEN": "token",
    "HINDDIAN_CA_FILE": "ca_file",
    "HINDDIAN_ALLOW_INSECURE": "allow_insecure",
}


def config_path() -> Path:
    env = os.environ.get("HINDDIAN_CONFIG")
    if env:
        return Path(env)
    xdg = os.environ.get("XDG_CONFIG_HOME")
    return (Path(xdg) if xdg else Path.home() / ".config") / "hinddian" / "config.json"


def load_config() -> dict[str, Any]:
    try:
        data = json.loads(config_path().read_text(encoding="utf-8"))
        return data if isinstance(data, dict) else {}
    except (OSError, ValueError):
        return {}


def save_config(cfg: dict[str, Any]) -> Path:
    p = config_path()
    p.parent.mkdir(parents=True, exist_ok=True)
    tmp = p.with_name(p.name + ".tmp")
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)  # holds the token
    with os.fdopen(fd, "w", encoding="utf-8") as fh:
        json.dump(cfg, fh, ensure_ascii=False, indent=2)
        fh.write("\n")
    os.replace(tmp, p)
    return p


def setting(name: str) -> str:
    v = os.environ.get(name) or os.environ.get("CLAUDE_PLUGIN_OPTION_" + name)
    if v is None or not str(v).strip():
        v = load_config().get(_FILE_KEYS[name])
    if isinstance(v, bool):
        return "1" if v else ""
    return str(v or "").strip()


def memory_url() -> str:
    return setting("HINDDIAN_MEMORY_URL").rstrip("/")


def token() -> str:
    return setting("HINDDIAN_MCP_TOKEN")


def transport_problem(url: str | None = None) -> str | None:
    """Why we must not talk to the server, or None if OK."""
    url = memory_url() if url is None else url
    if not url:
        return "hinddian not configured (run setup.py)"
    u = urllib.parse.urlsplit(url)
    if u.scheme == "https":
        return None
    if u.scheme == "http" and (u.hostname in LOOPBACK or setting("HINDDIAN_ALLOW_INSECURE") in ("1", "true")):
        return None
    return f"refusing plain {u.scheme or '?'}:// to {u.hostname or url} (use https, or HINDDIAN_ALLOW_INSECURE=1)"


def req(method: str, path: str, body: Any = None, timeout: float = 30) -> Any:
    why = transport_problem()
    if why:
        raise RuntimeError(why)
    headers = {"Accept": "application/json"}
    tok = token()
    if tok:
        headers["Authorization"] = f"Bearer {tok}"
    data = None
    if body is not None:
        headers["Content-Type"] = "application/json"
        data = json.dumps(body, ensure_ascii=False).encode()
    r = urllib.request.Request(memory_url() + path, data=data, headers=headers, method=method)
    with urllib.request.urlopen(r, timeout=timeout, context=_ssl_context()) as resp:
        return json.loads(resp.read())


def emit_context(event: str, text: str, payload: dict | None = None) -> None:
    """Hand text to the agent as hook context. Claude Code / Codex send `hook_event_name`
    and read `hookSpecificOutput.additionalContext`; other hosts (Magpie) take plain stdout."""
    if not text:
        return
    if payload and (payload.get("hook_event_name") or payload.get("hookEventName")):
        print(json.dumps({"hookSpecificOutput": {"hookEventName": event, "additionalContext": text}}, ensure_ascii=False))
    else:
        print(text)


def flag(name: str, default: bool) -> bool:
    """Boolean switch from env, else config file key (lower-case name without HINDDIAN_)."""
    v = os.environ.get(name)
    if v is None:
        v = load_config().get(name.removeprefix("HINDDIAN_").lower())
    if v is None or v == "":
        return default
    return str(v).strip().lower() not in ("0", "false", "no", "off")


def _ssl_context() -> ssl.SSLContext | None:
    ca = setting("HINDDIAN_CA_FILE")
    if not ca:
        return None
    ctx = ssl.create_default_context()
    ctx.load_verify_locations(cafile=ca)
    return ctx


def spawn_finalize(*args: str, log: Path) -> bool:
    """Run finalize.py detached so the host's hook returns immediately."""
    if os.environ.get("HINDDIAN_HOOK_SYNC") == "1":
        return False
    log.parent.mkdir(parents=True, exist_ok=True)
    if log.is_file() and log.stat().st_size > 512_000:
        log.replace(log.with_suffix(".log.1"))
    kw: dict[str, Any] = {"stdin": subprocess.DEVNULL, "close_fds": True}
    if os.name == "nt":
        kw["creationflags"] = 0x00000008 | 0x00000200  # DETACHED_PROCESS | CREATE_NEW_PROCESS_GROUP
    else:
        kw["start_new_session"] = True
    with open(log, "ab") as fh:
        subprocess.Popen([sys.executable, str(HERE / "finalize.py"), *args], stdout=fh, stderr=fh, **kw)
    return True
