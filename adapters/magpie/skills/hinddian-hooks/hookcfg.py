"""Shared config + HTTP client for host hooks (stdlib only; runs on every user machine).

Canonical source: hooks/ in the hinddian repo. Copies under plugins/, skills/ and adapters/
are generated by tools/sync_hooks.py — edit here, then run it.

No built-in server address: set HINDDIAN_MEMORY_URL (e.g. https://host/hinddian) and
HINDDIAN_MCP_TOKEN. Session text and the token are never sent over plain http to a
non-loopback host unless HINDDIAN_ALLOW_INSECURE=1. A self-signed / private-CA server cert is
trusted via HINDDIAN_CA_FILE (added to, not replacing, the system CAs).
"""
from __future__ import annotations

import json
import os
import ssl
import subprocess
import sys
import urllib.parse
import urllib.request
from pathlib import Path
from typing import Any

HERE = Path(__file__).resolve().parent
LOOPBACK = {"127.0.0.1", "localhost", "::1"}


def memory_url() -> str:
    return (os.environ.get("HINDDIAN_MEMORY_URL") or "").strip().rstrip("/")


def token() -> str:
    return (os.environ.get("HINDDIAN_MCP_TOKEN") or "").strip()


def transport_problem(url: str | None = None) -> str | None:
    """Why we must not talk to the server, or None if OK."""
    url = memory_url() if url is None else url
    if not url:
        return "HINDDIAN_MEMORY_URL not set"
    u = urllib.parse.urlsplit(url)
    if u.scheme == "https":
        return None
    if u.scheme == "http" and (u.hostname in LOOPBACK or os.environ.get("HINDDIAN_ALLOW_INSECURE") == "1"):
        return None
    return f"refusing plain {u.scheme or '?'}:// to {u.hostname or url} (use https, or HINDDIAN_ALLOW_INSECURE=1)"


def req(method: str, path: str, body: Any = None, timeout: float = 30) -> Any:
    why = transport_problem()
    if why:
        raise RuntimeError(why)
    headers = {"Accept": "application/json"}
    tok = token()
    if tok:
        headers["Authorization"] = f"Bearer {tok}"
    data = None
    if body is not None:
        headers["Content-Type"] = "application/json"
        data = json.dumps(body, ensure_ascii=False).encode()
    r = urllib.request.Request(memory_url() + path, data=data, headers=headers, method=method)
    with urllib.request.urlopen(r, timeout=timeout, context=_ssl_context()) as resp:
        return json.loads(resp.read())


def _ssl_context() -> ssl.SSLContext | None:
    ca = (os.environ.get("HINDDIAN_CA_FILE") or "").strip()
    if not ca:
        return None
    ctx = ssl.create_default_context()
    ctx.load_verify_locations(cafile=ca)
    return ctx


def spawn_finalize(*args: str, log: Path) -> bool:
    """Run finalize.py detached so the host's hook returns immediately."""
    if os.environ.get("HINDDIAN_HOOK_SYNC") == "1":
        return False
    log.parent.mkdir(parents=True, exist_ok=True)
    if log.is_file() and log.stat().st_size > 512_000:
        log.replace(log.with_suffix(".log.1"))
    kw: dict[str, Any] = {"stdin": subprocess.DEVNULL, "close_fds": True}
    if os.name == "nt":
        kw["creationflags"] = 0x00000008 | 0x00000200  # DETACHED_PROCESS | CREATE_NEW_PROCESS_GROUP
    else:
        kw["start_new_session"] = True
    with open(log, "ab") as fh:
        subprocess.Popen([sys.executable, str(HERE / "finalize.py"), *args], stdout=fh, stderr=fh, **kw)
    return True
